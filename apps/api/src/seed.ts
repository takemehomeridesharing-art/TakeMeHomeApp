/** Deletes every row (children first). Used by tests and `pnpm db:reset`. */
export async function wipe() {
  await prisma.$transaction([
    prisma.chatMessage.deleteMany(),
    prisma.rating.deleteMany(),
    prisma.sosEvent.deleteMany(),
    prisma.report.deleteMany(),
    prisma.booking.deleteMany(),
    prisma.payment.deleteMany(),
    prisma.payout.deleteMany(),
    prisma.joinRequest.deleteMany(),
    prisma.tripStop.deleteMany(),
    prisma.trip.deleteMany(),
    prisma.verificationRequest.deleteMany(),
    prisma.vehicle.deleteMany(),
    prisma.notification.deleteMany(),
    prisma.block.deleteMany(),
    prisma.otpChallenge.deleteMany(),
    prisma.devOutbox.deleteMany(),
    prisma.user.deleteMany(),
    prisma.place.deleteMany(),
  ]);
}

export async function seedIfEmpty(): Promise<boolean> {
  if ((await prisma.user.count()) > 0) return false;
  await seed();
  return true;
}
