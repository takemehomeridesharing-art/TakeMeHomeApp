const WEEKDAYS: Weekday[] = ['MO', 'TU', 'WE', 'TH', 'FR'];

async function createTrip(data: {
  driverId: string;
  vehicleId: string;
  departureTime: Date;
  stops: string[];
  seats: number;
  womenOnly?: boolean;
  isEV?: boolean;
  recurringDays?: Weekday[];
  seriesId?: string;
  status?: 'published' | 'completed';
}) {
  const corridor = buildCorridor(data.stops);
  return prisma.trip.create({
    data: {
      driverId: data.driverId,
      vehicleId: data.vehicleId,
      departureTime: data.departureTime,
      seriesId: data.seriesId,
      recurringDays: data.recurringDays as Prisma.InputJsonValue | undefined,
      seatsOffered: data.seats,
      womenOnly: data.womenOnly ?? false,
      isEV: data.isEV ?? false,
      totalKm: corridor[corridor.length - 1]!.cumulativeKm,
      status: data.status ?? 'published',
      ...(data.status === 'completed' ? { startedAt: data.departureTime, completedAt: new Date(data.departureTime.getTime() + 30 * 60_000) } : {}),
      stops: { create: corridor },
    },
    include: { stops: true },
  });
}

